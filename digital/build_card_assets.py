"""Build offline PNGs from the same cached LaTeX SVGs used by printed cards.

Build-time only: ReportLab, svglib, and pdftocairo. Run with a Python that has
ReportLab installed; the local Codex runtime and cached svglib are recognized.
Nothing in this script is required when launching the game.
"""

from io import BytesIO
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path.home() / ".cache/gametrix-pdf-deps"))
from reportlab.graphics import renderPDF
from reportlab.pdfgen import canvas
from svglib.svglib import svg2rlg
import card_art
from card_layout import OP_COPY

ASSETS = ROOT / "digital/assets"


def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    fonts = Path.home() / ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/pdfjs-dist/standard_fonts"
    for name in ("LiberationSans-Regular.ttf", "LiberationSans-Bold.ttf"):
        shutil.copyfile(fonts / name, ASSETS / name)
    shutil.copyfile(fonts / "LICENSE_LIBERATION", ASSETS / "LICENSE_LIBERATION")
    deck = json.loads((ROOT / "expansion_split/generated/deck.json").read_text())
    sources = {"operation_" + code: card_art.operation_art(code) for code in OP_COPY}
    for card in deck["objectives"]:
        sources["objective_" + card["id"]] = card_art.objective_art(card)
        sources["example_" + card["id"]] = card_art.matrix_art(card["A"])
    cache = card_art.load_cache()
    poppler = shutil.which("pdftocairo") or str(Path.home() / ".cache/codex-runtimes/codex-primary-runtime/dependencies/native/poppler/poppler/bin/pdftocairo")
    with tempfile.TemporaryDirectory(prefix="gametrix-art-") as temp:
        for name, source in sources.items():
            drawing = svg2rlg(BytesIO(cache[card_art.source_key(source)].encode()))
            if drawing is None:
                raise ValueError(f"Cannot convert {name}")
            pdf = Path(temp) / (name + ".pdf")
            page = canvas.Canvas(str(pdf), pagesize=(drawing.width, drawing.height))
            renderPDF.draw(drawing, page, 0, 0)
            page.save()
            subprocess.run([poppler, "-png", "-transp", "-singlefile", "-r", "240", str(pdf), str(ASSETS / name)], check=True, capture_output=True)
    (ASSETS / "README.txt").write_text(
        "Original GameTrix LaTeX/TikZ artwork from design/formula_cache.json.\n"
        "Generated by digital/build_card_assets.py; runtime uses only Pillow and Arcade.\n"
        "Liberation Sans fonts are bundled for consistent offline text rendering.\n"
    )
    print(f"Built {len(sources)} illustrations and two fonts in {ASSETS}")


if __name__ == "__main__":
    main()
